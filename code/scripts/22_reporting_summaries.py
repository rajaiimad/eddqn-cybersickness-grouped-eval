"""Descriptive summaries of existing results for the reporting of RQ2 and RQ3 (no model is trained).

* Reward ratio (RQ2): ROC-AUC of E-DDQN under the regret ratios 1:1 to 10:1
  (configurations fixed) and the largest difference from the 5:1 reward,
  from results/tables/ablation_ratio_summary.csv (rule D1, seed means).
* Perturbations (RQ3): decision-level changes at the fixed D1 thresholds for
  the twelve whole-session stress variants, and the clean false-positive rates
  from which the adaptive worst cases start, from
  results/tables/attack_summary.csv and attack_worst_case.csv.

Out: results/tables/reporting/{rq_macros.json, rq_macros.tex}
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from eddqn import RESULTS  # noqa: E402

TAB = RESULTS / "tables"
OUT = TAB / "reporting"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    M = {}
    # ---- reward ratio
    r = pd.read_csv(TAB / "ablation_ratio_summary.csv")
    ratio = r[(r.rule == "D1_min_cost") & r.model.str.startswith("RATIO")].set_index("model")
    auc = ratio.roc_auc_mean
    M["RQRatioAucMin"] = f"{auc.min():.3f}"
    M["RQRatioAucMax"] = f"{auc.max():.3f}"
    M["RQRatioAucMaxDiff"] = f"{(auc - auc.loc['RATIO 5']).abs().max():.3f}"
    M["RQRatioAucSdMax"] = f"{ratio.roc_auc_std.max():.3f}"
    # ---- perturbations at fixed thresholds, whole-session stress variants
    a = pd.read_csv(TAB / "attack_summary.csv")
    w = a[(a.window == "whole") & (a.role == "stress")]
    drec = 100 * (w.recall_attacked - w.recall_clean)
    dfpr = 100 * (w.fpr_attacked - w.fpr_clean)
    dcost = w.cost_attacked - w.cost_clean
    M["RQPertN"] = str(len(w))
    M["RQPertVariants"] = str(w[["kind", "value"]].drop_duplicates().shape[0])
    M["RQPertRecallMin"] = f"{drec.min():+.1f}".replace("-", "$-$")
    M["RQPertRecallMax"] = f"{drec.max():+.1f}".replace("-", "$-$")
    M["RQPertFprMin"] = f"{dfpr.min():+.1f}".replace("-", "$-$")
    M["RQPertFprMax"] = f"{dfpr.max():+.1f}".replace("-", "$-$")
    M["RQPertCostMin"] = f"{dcost.min():+.3f}".replace("-", "$-$")
    M["RQPertCostMax"] = f"{dcost.max():+.3f}".replace("-", "$-$")
    M["RQPertRecallSmallShare"] = f"{100 * (drec.abs() <= 2).mean():.0f}"
    # ---- adaptive worst case: clean baseline and increase
    wc = pd.read_csv(TAB / "attack_worst_case.csv")
    rise = 100 * (wc.fpr_worst_case_false_alarm - wc.fpr_clean)
    M["RQWorstCleanFprMin"] = f"{100 * wc.fpr_clean.min():.1f}"
    M["RQWorstCleanFprMax"] = f"{100 * wc.fpr_clean.max():.1f}"
    M["RQWorstFprRiseMin"] = f"{rise.min():.1f}"
    M["RQWorstFprRiseMax"] = f"{rise.max():.1f}"
    (OUT / "rq_macros.json").write_text(json.dumps(M, indent=1))
    (OUT / "rq_macros.tex").write_text("% generated by scripts/22_reporting_summaries.py -- do not edit\n" +
                                       "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(M.items())) + "\n")
    print(json.dumps(M, indent=1))


if __name__ == "__main__":
    main()
