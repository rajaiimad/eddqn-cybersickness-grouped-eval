"""Threshold-scale check of rule D1 for the seed ensemble (exploratory; no prior commitment).

scripts/16_threshold_scale.py checks the per-seed D1 results: the threshold is
chosen on pooled OOF scores of single inner models but applied to the mean of
three inner models' test scores.  The seed ensemble, used for every paired test
and interval, has the same structure: its threshold is chosen on the seed-mean
OOF score (each OOF value from one inner model per seed) and applied to the mean
over seeds and inner models.  Here the unchanged ensemble threshold is also
applied to the seed-mean test score of each single inner model.  No model is
trained and no threshold is re-chosen.

Out: results/tables/threshold_scale_ensemble/{tse.csv, tse_macros.tex, tse_macros.json}
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))
from eddqn import RESULTS  # noqa: E402
from eddqn.experiment import operating_thresholds  # noqa: E402
from eddqn.metrics import cost_of  # noqa: E402

spec = importlib.util.spec_from_file_location("aggregate", HERE / "04_aggregate.py")
AG = importlib.util.module_from_spec(spec)
sys.modules["aggregate"] = AG
spec.loader.exec_module(AG)

FAMS = ["E-DDQN", "E-CB", "DQN", "CS-MLP", "LogReg", "HGB", "RF"]
OUT = RESULTS / "tables" / "threshold_scale_ensemble"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    F = AG.Frames()
    rows = []
    for fam in FAMS:
        runs = AG.collect(fam, F)
        y_all, pipe, single = [], [], {j: [] for j in range(AG.KI)}
        for k in range(AG.KO):
            y = F.test[k].y.to_numpy()
            oof = np.mean([runs[(k, s)]["oof"].score.to_numpy() for s in AG.SEEDS], axis=0)
            thr = operating_thresholds(oof, runs[(k, AG.SEEDS[0])]["oof"].y.to_numpy(), AG.PROTOCOL)["D1_min_cost"]
            te = np.array([[AG.load(AG.RUNS / fam / f"o{k}_s{s}_i{j}.pkl")["test_score"] for j in range(AG.KI)]
                           for s in AG.SEEDS])                     # seeds x inner models x samples
            y_all.append(y)
            pipe.append((te.mean(axis=(0, 1)) >= thr).astype(int))
            for j in range(AG.KI):
                single[j].append((te[:, j].mean(axis=0) >= thr).astype(int))
        y_all = np.concatenate(y_all)
        rows.append({"family": fam, "ens_cost_reported": cost_of(np.concatenate(pipe), y_all),
                     "ens_cost_single_inner": float(np.mean([cost_of(np.concatenate(single[j]), y_all) for j in range(AG.KI)]))})
    d = pd.DataFrame(rows).set_index("family")
    d["delta"] = d.ens_cost_single_inner - d.ens_cost_reported
    published = pd.read_csv(AG.PRED / "E-DDQN.csv.gz", dtype={"seed": str})
    e = published[published.seed == "ens"]
    assert abs(cost_of(e.pred_D1_min_cost.to_numpy(), e.y.to_numpy()) - d.loc["E-DDQN", "ens_cost_reported"]) < 1e-12, \
        "reported ensemble cost not reproduced"
    d.to_csv(OUT / "tse.csv")
    rep, sing = list(d.ens_cost_reported.sort_values().index), list(d.ens_cost_single_inner.sort_values().index)
    moved = [f for f in FAMS if rep.index(f) != sing.index(f)]
    M = {"TSEEDDQNRep": f"{d.loc['E-DDQN', 'ens_cost_reported']:.3f}", "TSEEDDQNSingle": f"{d.loc['E-DDQN', 'ens_cost_single_inner']:.3f}",
         "TSERFRep": f"{d.loc['RF', 'ens_cost_reported']:.3f}", "TSERFSingle": f"{d.loc['RF', 'ens_cost_single_inner']:.3f}",
         "TSEGapRep": f"{d.loc['E-DDQN', 'ens_cost_reported'] - d.loc['RF', 'ens_cost_reported']:+.3f}",
         "TSEGapSingle": f"{d.loc['E-DDQN', 'ens_cost_single_inner'] - d.loc['RF', 'ens_cost_single_inner']:+.3f}",
         "TSEFirstSame": "yes" if rep[0] == sing[0] else "no", "TSELastSame": "yes" if rep[-1] == sing[-1] else "no",
         "TSEFirst": sing[0], "TSELast": sing[-1], "TSEMoved": ", ".join(moved) or "none", "TSEMovedN": str(len(moved)),
         "TSENeuralDeltaMin": f"{d.loc[['E-DDQN', 'E-CB', 'DQN', 'CS-MLP'], 'delta'].min():+.3f}",
         "TSENeuralDeltaMax": f"{d.loc[['E-DDQN', 'E-CB', 'DQN', 'CS-MLP'], 'delta'].max():+.3f}"}
    (OUT / "tse_macros.json").write_text(json.dumps(M, indent=1))
    (OUT / "tse_macros.tex").write_text("% generated by scripts/21_threshold_scale_ensemble.py -- do not edit\n" +
                                        "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(M.items())) + "\n")
    print(d.round(4).to_string())
    print(json.dumps(M, indent=1))


if __name__ == "__main__":
    main()
